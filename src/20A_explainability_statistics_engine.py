"""
20A_explainability_statistics_engine.py

BrainFMOps Phase 3
Explainability Statistics Engine for Professional Grad-CAM Outputs

Purpose
-------
This module summarizes Grad-CAM outputs generated by:
19A_gradcam_professional.py

It performs:
1. Input validation for gradcam_summary.csv.
2. Overall and category-level descriptive statistics.
3. Correct-vs-incorrect comparison.
4. Normal-vs-dementia comparison.
5. Bootstrap confidence intervals for explainability statistics.
6. Nonparametric effect-size estimation.
7. Correlation analysis between confidence, entropy, and activation metrics.
8. Publication-ready tables and figures.
9. A reproducible JSON/TXT report.

Scientific caution
------------------
This module quantifies Grad-CAM maps. It does not validate anatomical correctness,
clinical localization, or causal reasoning. Any anatomical interpretation still
requires expert review and, ideally, atlas-based validation.

Example
-------
python 20A_explainability_statistics_engine.py ^
  --gradcam-summary "outputs/gradcam_professional_v1/gradcam_summary.csv" ^
  --output-dir "outputs/explainability_statistics_v1" ^
  --bootstrap 2000 ^
  --seed 42
"""

